// Writes supabase/seed.sql from the hand-entered starter places in src/data/seed.ts.
// Run: npm run seed:sql   (then paste into the Supabase SQL editor, or `supabase db reset` locally)

import { writeFileSync } from "node:fs";
import { SEED_PLACES } from "../src/data/seed.ts";

const q = (v: unknown) => (v === undefined || v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => (v === undefined || v === null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (v: string[] | undefined) => `array[${(v ?? []).map(q).join(", ")}]::text[]`;

const lines = ["-- Generated by scripts/seed-to-sql.ts. Safe to re-run: updates existing rows.", "begin;"];
for (const p of SEED_PLACES) {
  lines.push(
    `insert into public.places (id, name, kind, region, area, address, location, approximate_location, default_status, default_source, features, notes, hazards, origin)
values (${q(p.id)}, ${q(p.name)}, ${q(p.kind)}, ${q(p.region)}, ${q(p.area)}, ${q(p.address)}, extensions.st_setsrid(extensions.st_makepoint(${p.lon}, ${p.lat}), 4326)::extensions.geography, ${p.approximateLocation ? "true" : "false"}, ${q(p.defaultStatus)}, ${j(p.defaultSource)}, ${j(p.features)}, ${arr(p.notes)}, ${arr(p.hazards)}, 'manual')
on conflict (id) do update set name = excluded.name, kind = excluded.kind, region = excluded.region, area = excluded.area, address = excluded.address,
  location = excluded.location, approximate_location = excluded.approximate_location, default_status = excluded.default_status,
  default_source = excluded.default_source, features = excluded.features, notes = excluded.notes, hazards = excluded.hazards;`,
  );
  lines.push(`delete from public.rules where place_id = ${q(p.id)};`);
  for (const r of p.rules) {
    lines.push(
      `insert into public.rules (id, place_id, status, days, time_window, season, priority, note, source) values (${q(p.id + ":" + r.id)}, ${q(p.id)}, ${q(r.status)}, ${j(r.days)}, ${j(r.window)}, ${j(r.season)}, ${r.priority ?? "null"}, ${q(r.note)}, ${j(r.source)});`,
    );
  }
}
lines.push("commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log(`Wrote supabase/seed.sql with ${SEED_PLACES.length} places.`);
